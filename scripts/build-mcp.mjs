/**
 * Bundles the MCP server (src/mcp/server.ts) into the one file the Supabase
 * Edge Function imports.
 *
 * The server shares the generator, the day transforms and the rules with the
 * app — they are the same modules under src/ — and Deno cannot import those
 * as they are written (extensionless relative imports, npm dependencies).
 * Bundling at deploy time keeps a single copy of that logic; the previous
 * Edge Functions carried their own, and it went stale.
 *
 * The output is not committed. `npm run build:mcp` writes it, and the deploy
 * workflow runs that right before `supabase functions deploy`.
 */
import { build } from 'esbuild'

await build({
  entryPoints: ['src/mcp/server.ts'],
  outfile: 'supabase/functions/mcp/bundle.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-mcp.mjs from src/mcp/. Do not edit.' },
})
console.log('Built supabase/functions/mcp/bundle.js')
